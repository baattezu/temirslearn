export function LessonIcon({ id, trackColor, className }: { id: string; trackColor?: string; className?: string }) {
  const [track, slug] = id.split("/");
  const d = BY_ID[id] ?? BY_SLUG[slug];
  if (!d) return <TrackIcon id={track} color={trackColor} className={className} />;
  if ("brand" in d) {
    return (
      <svg viewBox="0 0 24 24" className={className} fill={d.color} aria-hidden>
        <path d={d.brand.path} />
      </svg>
    );
  }
  const I = d;
  return <I className={className} style={{ color: trackColor }} strokeWidth={1.8} aria-hidden />;
}
